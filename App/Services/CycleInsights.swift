import Foundation

// MARK: - Fixed costs

/// Expenses paid in lump sums — rent, bills, installments — as opposed to spending that is spread
/// over the days of the cycle (food, transport, coffee). The daily plan takes fixed costs out of the
/// budget up front instead of dividing them by day, so paying the rent does not wreck "today".
struct FixedCosts: Equatable {
    /// A recurring expense that has not been booked as a transaction yet.
    struct Planned: Equatable {
        let date: Date
        let amount: Int64
    }

    struct Totals: Equatable {
        /// Fixed expenses already booked in the cycle.
        let spent: Int64
        /// Recurring expenses still to come in the cycle.
        let reserved: Int64
        var total: Int64 { spent &+ reserved }
        static let zero = Totals(spent: 0, reserved: 0)
    }

    /// Nothing is fixed: the whole budget is spread over the days.
    static let none = FixedCosts(countsRecurring: false)

    /// Expense categories marked fixed.
    var categoryIDs: Set<UUID> = []
    /// Upcoming recurring expense occurrences (after each rule's generation cursor).
    var planned: [Planned] = []
    /// Expenses generated by a recurring rule are fixed.
    var countsRecurring = true

    func isFixed(_ transaction: Transaction) -> Bool {
        guard transaction.kindRaw == TransactionKind.expense.rawValue else { return false }
        if countsRecurring, transaction.recurrenceKey != nil { return true }
        return transaction.category.map { categoryIDs.contains($0.id) } ?? false
    }

    /// Fixed spending booked in `month` plus what recurring rules will still charge in it.
    func totals(month: ReportingMonth, transactions: [Transaction]) throws -> Totals {
        let interval = month.interval
        let spent = try BalanceCalculator.flowTotals(transactions: transactions.filter(isFixed), during: interval,
                                                     allowMissingCategory: true).expense
        var reserved: Int64 = 0
        for item in planned where item.date >= interval.start && item.date < interval.end {
            let sum = reserved.addingReportingOverflow(item.amount)
            guard !sum.overflow else { throw BalanceCalculator.CalculationError.overflow }
            reserved = sum.partialValue
        }
        guard !spent.addingReportingOverflow(reserved).overflow else { throw BalanceCalculator.CalculationError.overflow }
        return Totals(spent: spent, reserved: reserved)
    }

    /// Fixed categories plus the not-yet-generated occurrences of active recurring expenses in `month`.
    static func make(categories: [Category], rules: [RecurringRule], month: ReportingMonth) -> FixedCosts {
        let interval = month.interval
        var planned: [Planned] = []
        for rule in rules where !rule.isPaused {
            guard let draft = rule.draft, draft.transaction.kind == .expense else { continue }
            // Only occurrences inside the cycle that the generator has not booked yet.
            let floor = interval.start.addingTimeInterval(-1)
            let after = max(rule.generatedThrough ?? floor, floor)
            let dates = RecurrenceCalculator.occurrences(start: draft.startDate, frequency: draft.frequency, interval: draft.interval,
                                                         end: draft.endDate, after: after, through: month.lastDay, limit: 62)
            planned += dates.filter { $0 >= interval.start && $0 < interval.end }.map { Planned(date: $0, amount: rule.amount) }
        }
        let fixed = categories.filter { $0.isFixed && $0.kindRaw == TransactionKind.expense.rawValue }.map(\.id)
        return FixedCosts(categoryIDs: Set(fixed), planned: planned)
    }
}

// MARK: - Flexible daily allowance

extension StatsService {
    /// "How much may I still spend today": the flexible part of the budget (total limit minus fixed
    /// costs, booked or still to come) left at the start of today, spread over the days left in the
    /// cycle (today included). Fixed costs never count as "today's" spending. Unlike `dailyAllowance`
    /// it adapts — overspending yesterday lowers today's figure, saving raises it.
    struct FlexibleAllowance: Equatable {
        let limit: Int64
        /// Fixed expenses already paid this cycle.
        let fixedSpent: Int64
        /// Recurring expenses still to come this cycle, set aside up front.
        let fixedReserved: Int64
        /// Flexible spending before today.
        let spentBeforeToday: Int64
        /// Flexible spending today; fixed expenses paid today are not included.
        let spentToday: Int64
        /// Days left in the cycle, today included; at least 1.
        let daysLeft: Int
        /// Flexible budget left at the start of today ÷ days left; 0 once it is used up.
        let perDay: Int64
        /// `perDay − spentToday`; negative when today already went over.
        let leftToday: Int64
        /// Flexible budget left in the cycle after today's spending; negative when over.
        let leftInCycle: Int64

        var fixedTotal: Int64 { fixedSpent &+ fixedReserved }
        /// The part of the limit meant to be spread over the days.
        var flexibleLimit: Int64 { limit &- fixedTotal }
    }

    /// Nil when `now` is outside `month`: the figure only makes sense for the running cycle.
    static func flexibleAllowance(limit: Int64, month: ReportingMonth, transactions: [Transaction],
                                  fixed: FixedCosts = .none, now: Date = Date()) throws -> FlexibleAllowance? {
        let interval = month.interval
        guard limit > 0, now >= interval.start, now < interval.end else { return nil }
        let calendar = LocalCalendar.calendar
        let today = calendar.startOfDay(for: now)
        let tomorrow = calendar.date(byAdding: .day, value: 1, to: today)!
        let fixedTotals = try fixed.totals(month: month, transactions: transactions)
        let flexible = transactions.filter { !fixed.isFixed($0) }
        let before = try BalanceCalculator.flowTotals(transactions: flexible, during: DateInterval(start: interval.start, end: today),
                                                      allowMissingCategory: true).expense
        let todaySpent = try BalanceCalculator.flowTotals(transactions: flexible, during: DateInterval(start: today, end: tomorrow),
                                                          allowMissingCategory: true).expense
        let daysLeft = max(1, calendar.dateComponents([.day], from: today, to: interval.end).day!)
        let flexibleLimit = limit.subtractingReportingOverflow(fixedTotals.total)
        let remaining = flexibleLimit.partialValue.subtractingReportingOverflow(before)
        let cycleLeft = remaining.partialValue.subtractingReportingOverflow(todaySpent)
        guard !flexibleLimit.overflow, !remaining.overflow, !cycleLeft.overflow else { throw BalanceCalculator.CalculationError.overflow }
        let perDay = max(0, remaining.partialValue) / Int64(daysLeft)
        let leftToday = perDay.subtractingReportingOverflow(todaySpent)
        guard !leftToday.overflow else { throw BalanceCalculator.CalculationError.overflow }
        return FlexibleAllowance(limit: limit, fixedSpent: fixedTotals.spent, fixedReserved: fixedTotals.reserved,
                                 spentBeforeToday: before, spentToday: todaySpent, daysLeft: daysLeft,
                                 perDay: perDay, leftToday: leftToday.partialValue, leftInCycle: cycleLeft.partialValue)
    }
}

// MARK: - End-of-cycle summary

/// A look back at a finished (payday) month: totals, savings, top categories and budgets.
struct CycleSummary {
    let month: ReportingMonth
    let report: StatsService.Report
    /// Against the cycle before; nil when that one cannot be computed.
    let comparison: StatsService.Comparison?
    let topExpenses: [StatsService.CategoryTotal]
    let budgets: [BudgetService.Progress]

    var saved: Int64 { report.difference }
    /// Share of income kept, in tenths of a percent; nil without income.
    var savedRateTenths: Int? {
        guard report.income > 0 else { return nil }
        return StatsPercentage.tenths(amount: max(0, min(report.difference, report.income)), total: report.income)
    }
    var overBudget: [BudgetService.Progress] { budgets.filter { $0.level == .over } }
    var totalBudget: BudgetService.Progress? { budgets.first { $0.scope == .total } }

    static func make(month: ReportingMonth, transactions: [Transaction], rules: [BudgetRule]) throws -> CycleSummary {
        let report = try StatsService.report(month: month, transactions: transactions)
        // `now` after the cycle: compare whole cycles, not elapsed days.
        let comparison = try? StatsService.comparison(month: month, now: month.interval.end, transactions: transactions)
        return CycleSummary(month: month, report: report, comparison: comparison, topExpenses: Array(report.expenses.prefix(3)),
                            budgets: try BudgetService.progress(month: month, rules: rules, transactions: transactions))
    }
}

/// Shows the summary once, on the first launch after a cycle ends.
enum CycleSummaryTracker {
    static let lastShownKey = "SaveMoney.cycleSummary.lastShown"

    static func identifier(_ month: ReportingMonth) -> String { String(format: "%04d-%02d", month.year, month.month) }

    /// The cycle that just ended, if it had transactions and its summary has not been shown yet.
    static func pending(now: Date = Date(), transactions: [Transaction], defaults: UserDefaults = .standard) -> ReportingMonth? {
        guard let previous = ReportingMonth(containing: now).previous,
              defaults.string(forKey: lastShownKey) != identifier(previous) else { return nil }
        let interval = previous.interval
        guard transactions.contains(where: { $0.date >= interval.start && $0.date < interval.end }) else { return nil }
        return previous
    }

    static func markShown(_ month: ReportingMonth, defaults: UserDefaults = .standard) {
        defaults.set(identifier(month), forKey: lastShownKey)
    }
}

// MARK: - Widget snapshot

extension WidgetSnapshot {
    /// Builds the widget summary for the running cycle. Amounts are omitted unless `showsAmounts`.
    static func make(transactions: [Transaction], totalBalance: Int64, rules: [BudgetRule], fixed: FixedCosts = .none,
                     showsAmounts: Bool, now: Date = Date()) -> WidgetSnapshot {
        let calendar = LocalCalendar.calendar
        let month = ReportingMonth(containing: now)
        let today = calendar.startOfDay(for: now)
        let daysLeft = max(1, calendar.dateComponents([.day], from: today, to: month.interval.end).day!)
        var snapshot = WidgetSnapshot(generatedAt: now, day: today, cycleName: month.shortName, daysLeft: daysLeft, showsAmounts: showsAmounts)
        let total = (try? BudgetService.progress(month: month, rules: rules, transactions: transactions))?.first { $0.scope == .total }
        if let total {
            snapshot.budgetFraction = Double(total.spent) / Double(total.limit)
            snapshot.budgetLevel = total.level.rawValue
        }
        guard showsAmounts else { return snapshot }
        snapshot.totalBalance = totalBalance
        if let total {
            snapshot.cycleSpent = total.spent
            snapshot.cycleLimit = total.limit
            if let allowance = try? StatsService.flexibleAllowance(limit: total.limit, month: month, transactions: transactions,
                                                                    fixed: fixed, now: now) {
                snapshot.todayLeft = allowance.leftToday
                snapshot.perDay = allowance.perDay
                snapshot.spentToday = allowance.spentToday
            }
        }
        if snapshot.spentToday == nil {
            let tomorrow = calendar.date(byAdding: .day, value: 1, to: today)!
            snapshot.spentToday = try? BalanceCalculator.flowTotals(transactions: transactions, during: DateInterval(start: today, end: tomorrow),
                                                                    allowMissingCategory: true).expense
        }
        return snapshot
    }
}
